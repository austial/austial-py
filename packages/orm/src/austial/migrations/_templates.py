"""Bundled Alembic scaffolding templates.

Kept in-module (rather than as package data files) so a wheel install never has to worry
about ``importlib.resources`` lookups falling through, and so the templates stay in one
place next to the code that emits them via :meth:`MigrationRunner.init`.

The ``env.py`` template intentionally does nothing beyond calling :func:`alembic_env` --
that helper is what future changes to how migrations run online/offline route through, so
that upgrade path stays inside the framework rather than in every product's copy of
``env.py``.
"""

from __future__ import annotations

ENV_PY_TEMPLATE = '''"""Alembic env.py -- generated by ``austial-migrate init``.

Delegates the real work to :func:`austial.migrations.alembic_env`, so that whatever
online/offline conventions the framework settles on stay in one place. The only product
concern here is pointing ``target_metadata`` at the SQLAlchemy metadata your
``DataSource`` exposes (see the ``austial.migrations`` docs page for the recommended
import path).
"""

from __future__ import annotations

from logging.config import fileConfig

from alembic import context

from austial.migrations import alembic_env

# ---------------------------------------------------------------------------
# Product wires up ``target_metadata`` here. Two supported shapes:
#
#   1. Pass ``metadata=`` when constructing ``MigrationRunner``. That value is set on
#      ``context.config.attributes["target_metadata"]`` before ``alembic`` invokes this
#      file, so the ``.get(...)`` call below picks it up automatically.
#
#   2. When invoked via the standalone ``austial-migrate`` CLI, set
#      ``AUSTIAL_METADATA_MODULE=my_pkg.app_module:target_metadata`` -- the CLI imports
#      that dotted path and forwards it the same way.
#
target_metadata = context.config.attributes.get("target_metadata")

if context.config.config_file_name is not None:
    try:
        fileConfig(context.config.config_file_name)
    except Exception:  # noqa: BLE001 -- the .ini file is optional, missing logging config is not fatal.
        pass


alembic_env(context.config, target_metadata)
'''


