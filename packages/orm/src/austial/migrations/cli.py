"""``austial-migrate`` -- a standalone Typer app for driving migrations from a shell.

Deliberately separate from ``austial.cli`` (the framework's dev/scaffold CLI): a
migration run is often the first thing to happen at deploy time, before the app itself
imports cleanly, so the migration CLI must not depend on booting the DI container.

Configuration precedence:

1. Explicit ``--url`` flag.
2. ``AUSTIAL_DATABASE_URL`` env var.
3. ``sqlalchemy.url`` in a local ``alembic.ini`` next to the invocation cwd.

For autogenerate, the CLI also needs the SQLAlchemy metadata -- point at it with
``AUSTIAL_METADATA_MODULE`` (``dotted.module:attribute``). Every other subcommand works
without metadata.
"""

from __future__ import annotations

import configparser
import importlib
import os
import sys
from pathlib import Path
from typing import Annotated

import typer

from austial.migrations.config import MigrationsConfig
from austial.migrations.errors import MigrationConfigurationError
from austial.migrations.migration_runner import MigrationRunner

app = typer.Typer(
    name="austial-migrate",
    help="Alembic-backed schema migrations for austial.orm entities.",
    no_args_is_help=True,
    add_completion=False,
)


def _load_url(explicit: str | None) -> str:
    if explicit:
        return explicit
    env = os.environ.get("AUSTIAL_DATABASE_URL")
    if env:
        return env
    ini_path = Path("alembic.ini")
    if ini_path.exists():
        parser = configparser.ConfigParser()
        parser.read(ini_path)
        if parser.has_option("alembic", "sqlalchemy.url"):
            return parser.get("alembic", "sqlalchemy.url")
    raise MigrationConfigurationError(
        "No database URL. Pass --url, set AUSTIAL_DATABASE_URL, or add sqlalchemy.url to alembic.ini."
    )


def _load_config(script_location: str | None) -> MigrationsConfig:
    location = script_location or os.environ.get("AUSTIAL_MIGRATIONS_SCRIPT_LOCATION")
    if not location:
        ini_path = Path("alembic.ini")
        if ini_path.exists():
            parser = configparser.ConfigParser()
            parser.read(ini_path)
            if parser.has_option("alembic", "script_location"):
                location = parser.get("alembic", "script_location")
    return MigrationsConfig(script_location=location or "alembic")


def _load_metadata():
    dotted = os.environ.get("AUSTIAL_METADATA_MODULE")
    if not dotted:
        return None
    module_name, _, attr = dotted.partition(":")
    if not attr:
        raise MigrationConfigurationError(
            "AUSTIAL_METADATA_MODULE must be `module:attribute`, e.g. `src.app.app_module:target_metadata`."
        )
    sys.path.insert(0, os.getcwd())
    try:
        module = importlib.import_module(module_name)
    finally:
        sys.path.pop(0)
    try:
        return getattr(module, attr)
    except AttributeError as exc:
        raise MigrationConfigurationError(
            f"Module `{module_name}` has no attribute `{attr}` -- check AUSTIAL_METADATA_MODULE."
        ) from exc


def _make_runner(url: str | None, script_location: str | None) -> MigrationRunner:
    return MigrationRunner(
        _load_url(url),
        _load_config(script_location),
        metadata=_load_metadata(),
    )


@app.command()
def init(
    script_location: Annotated[str | None, typer.Option("--script-location", "-s")] = None,
) -> None:
    """Scaffold the ``script_location`` directory with ``env.py`` and ``versions/``."""
    cfg = _load_config(script_location)
    runner = MigrationRunner("sqlite:///:memory:", cfg)
    path = runner.init()
    typer.echo(f"Initialised migration scripts at {path}")


@app.command()
def revision(
    message: Annotated[str, typer.Option("--message", "-m", help="Human-readable revision message.")],
    autogenerate: Annotated[bool, typer.Option("--autogenerate/--no-autogenerate")] = True,
    url: Annotated[str | None, typer.Option("--url")] = None,
    script_location: Annotated[str | None, typer.Option("--script-location", "-s")] = None,
) -> None:
    """Create a new revision file (autogenerated against the current DB by default)."""
    runner = _make_runner(url, script_location)
    rev_id = runner.revision(message, autogenerate=autogenerate)
    typer.echo(rev_id)


@app.command()
def upgrade(
    target: Annotated[str, typer.Argument()] = "head",
    url: Annotated[str | None, typer.Option("--url")] = None,
    script_location: Annotated[str | None, typer.Option("--script-location", "-s")] = None,
) -> None:
    """Apply migrations up to ``target`` (default: ``head``)."""
    runner = _make_runner(url, script_location)
    runner.upgrade(target)


@app.command()
def downgrade(
    target: Annotated[str, typer.Argument()] = "-1",
    url: Annotated[str | None, typer.Option("--url")] = None,
    script_location: Annotated[str | None, typer.Option("--script-location", "-s")] = None,
) -> None:
    """Undo migrations back to ``target`` (default: ``-1`` -- one step back)."""
    runner = _make_runner(url, script_location)
    runner.downgrade(target)


@app.command()
def current(
    url: Annotated[str | None, typer.Option("--url")] = None,
    script_location: Annotated[str | None, typer.Option("--script-location", "-s")] = None,
) -> None:
    """Print the currently-applied revision id."""
    runner = _make_runner(url, script_location)
    rev = runner.current()
    typer.echo(rev or "")


@app.command()
def history(
    url: Annotated[str | None, typer.Option("--url")] = None,
    script_location: Annotated[str | None, typer.Option("--script-location", "-s")] = None,
) -> None:
    """List every revision, newest first."""
    runner = _make_runner(url, script_location)
    for entry in runner.history():
        marker = " (head)" if entry["is_head"] else ""
        down = entry["down_revision"] or "-"
        typer.echo(f"{entry['revision']} <- {down}  {entry['message']}{marker}")


if __name__ == "__main__":  # pragma: no cover
    app()
